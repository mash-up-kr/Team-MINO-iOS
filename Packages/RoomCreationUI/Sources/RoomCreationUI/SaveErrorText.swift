/// 이 패키지의 두 화면(방 만들기·친구 초대)이 함께 쓰는 실패 안내 문구.
///
/// 문구 자체를 상수로 묶는 이유는 **갈래가 아니라 표현이 같기 때문**이다. 어떤 `DomainError` 를
/// 어느 문구로 보낼지는 화면마다 다르지만(방은 저장 실패, 초대는 링크 실패), "세션이 끊겼다" 는
/// 두 화면이 똑같이 말해야 한다. 따로 적어 두면 한쪽만 다듬는 순간 조용히 갈라진다.
///
/// > `ProfileSetupUI` 에도 같은 문구가 한 벌 더 있다. 패키지가 달라 여기서 못 잇는다 —
/// > 두 패키지가 함께 보는 자리가 생기면 그때 올린다(후속).
enum SaveErrorText {
    /// 재시도를 권하지 않는다 — 세션이 끊긴 상태라 다시 눌러도 같은 실패다.
    static let sessionExpired = "로그인이 만료됐어요. 앱을 다시 열어주세요."
    static let saveFailed = "저장하지 못했어요. 잠시 후 다시 시도해주세요."
}
