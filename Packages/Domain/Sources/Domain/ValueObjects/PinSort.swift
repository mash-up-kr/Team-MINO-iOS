import Foundation

/// 방 상세·방 리스트의 지도 위 정렬 드롭다운 기준. **선언 순서가 곧 드롭다운 노출 순서**다
/// (시안 `2542:125333` 의 펼친 드롭다운: 꾹 Pick / 전체 / 최신순 / 거리순 / 코멘트순).
///
/// 홈 덱의 ``PinFilter`` 와 **case 가 달라 재사용하지 않는다** — 홈은 3종(`꾹 Pick`·`최신순`
/// ·`가까운순`)이고 이쪽은 `전체`·`코멘트순`이 더 있다. 서버도 엔드포인트마다 다른 enum 을 받는다.
///
/// **후보 선정과 순위는 서버가 정한다.** 앱은 기준 하나를 지정해 요청하고 받은 순서를 그대로
/// 그린다 — 재정렬하지도, 걸러내지도 않는다(PRD 「목록 정렬 기준」). `상위 30%`·`3km` 같은
/// 임계값은 서버 계약이 소유하므로 여기에도, 화면에도 두지 않는다.
///
/// 서버 `sort` 파라미터로 옮기는 매핑은 Data 계층 한 자리(`PinAPI`)에만 있다 — Domain 이 API
/// 스키마를 알지 못하게 한다. 그래서 rawValue 를 두지 않는다(있으면 그게 wire 값인 줄 오인한다).
public enum PinSort: CaseIterable, Equatable, Hashable, Sendable {
    /// 꾹 Pick — 오래 들여다보지 않은 순.
    case recommended
    /// 전체 — 거르지 않은 전부. **기본값이다**(PRD "5종이며 기본값은 `전체`다").
    case all
    /// 최신순 — 저장 시각 기준.
    case latest
    /// 거리순 — 내 기준 가까운 순. 좌표가 **필수**다(없이 보내면 서버가 거절한다).
    case distance
    /// 코멘트순 — 코멘트 많은 순.
    case comment

    /// 이 기준이 내 위치를 필요로 하는가. 화면이 좌표를 먼저 받아야 할지 판단하는 데 쓴다.
    public var requiresOrigin: Bool { self == .distance }
}
